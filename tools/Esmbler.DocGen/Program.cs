using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Schema;
using Esmbler.Sdk.Overlay;
using Esmbler.Sdk.Registry;
using Esmbler.Sdk.Specs;

var check = args.Contains("--check");
var root = FindRoot();
var outputs = new Dictionary<string, string>(StringComparer.Ordinal);

// 1. JSON Schema 2020-12 for every spec object, generated from the SDK types.
var specTypes = new (string Name, Type Type)[]
{
    ("module", typeof(ModuleSpec)), ("entity", typeof(EntitySpec)), ("field", typeof(FieldSpec)), ("choice_list", typeof(ChoiceListSpec)),
    ("relationship", typeof(RelationshipSpec)), ("rule", typeof(RuleSpec)), ("workflow", typeof(WorkflowSpec)), ("view", typeof(ViewSpec)),
    ("node", typeof(NodeSpec)), ("role", typeof(RoleSpec)), ("permission_set", typeof(PermissionSetSpec)), ("assignment_rule", typeof(AssignmentRuleSpec)),
    ("notification_template", typeof(NotificationTemplateSpec)), ("extension_point", typeof(ExtensionPointSpec)), ("migration", typeof(MigrationSpec)),
    ("catalog_item", typeof(CatalogItemSpec)), ("request_binding", typeof(RequestBindingSpec)), ("approval_policy", typeof(ApprovalPolicySpec)), ("event_type", typeof(EventTypeSpec)), ("business_calendar", typeof(BusinessCalendarSpec)), ("sla_policy", typeof(SlaPolicySpec)), ("overlay_op", typeof(OverlayOp)),
};
var exporterOptions = new JsonSchemaExporterOptions
{
    TreatNullObliviousAsNonNullable = true,
    TransformSchemaNode = (ctx, node) =>
    {
        if (ctx.Path.IsEmpty && node is JsonObject o)
        {
            o.Insert(0, "$schema", "https://json-schema.org/draft/2020-12/schema");
        }

        return node;
    },
};
foreach (var (name, type) in specTypes)
{
    var schema = SpecJson.Options.GetJsonSchemaAsNode(type, exporterOptions).AsObject();
    schema.Insert(1, "$id", $"https://schemas.esmbler.dev/specs/{name}.schema.json");
    schema.Insert(2, "title", type.Name);
    outputs[$"docs/reference/schemas/{name}.schema.json"] = schema.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";
}

// 2. Element catalog.
var registry = ElementRegistry.LoadBuiltIn();
var md = new StringBuilder();
md.AppendLine("""
---
title: Element catalog (generated)
status: generated
owner: platform-architecture
last_reviewed: generated
requirements: [REQ-EL-001, REQ-AI-002]
---

# Element catalog

Generated by `tools/Esmbler.DocGen` from `packages/Esmbler.Sdk/Registry/Elements/*.json`. Do not edit by hand; run `dotnet run --project tools/Esmbler.DocGen`. The schema is explained in [element-registry-schema.md](element-registry-schema.md).

""");
foreach (var group in registry.All.GroupBy(e => e.Category).OrderBy(g => CategoryOrder(g.Key)))
{
    md.AppendLine($"## {CategoryTitle(group.Key)}").AppendLine();
    md.AppendLine("| Element | Gate | Placeable | Description |").AppendLine("| --- | --- | --- | --- |");
    foreach (var e in group.OrderBy(e => e.Id, StringComparer.Ordinal))
    {
        md.AppendLine($"| `{e.Id}` | {e.Gate} | {(e.Placeable ? "yes" : "no")} | {Escape(FirstSentence(e.Description))} |");
    }

    md.AppendLine();
    foreach (var e in group.OrderBy(e => e.Id, StringComparer.Ordinal))
    {
        md.AppendLine($"### {e.Label} (`{e.Id}`)").AppendLine();
        md.AppendLine(e.Description).AppendLine();
        if (e.PropsSchema["properties"] is JsonObject props && props.Count > 0)
        {
            var required = (e.PropsSchema["required"] as JsonArray)?.Select(r => r!.GetValue<string>()).ToHashSet() ?? [];
            md.AppendLine("| Prop | Type | Required | Notes |").AppendLine("| --- | --- | --- | --- |");
            foreach (var (prop, schema) in props)
            {
                md.AppendLine($"| `{prop}` | {Escape(TypeOf(schema))} | {(required.Contains(prop) ? "yes" : "no")} | {Escape(schema?["description"]?.GetValue<string>() ?? string.Empty)} |");
            }

            md.AppendLine();
        }

        if (e.AllowedParents.Count > 0 || e.AllowedChildren.Count > 0)
        {
            md.AppendLine($"Parents: {List(e.AllowedParents)}. Children: {List(e.AllowedChildren)}.").AppendLine();
        }

        if (e.Constraints.Count > 0)
        {
            md.AppendLine("Constraints:").AppendLine();
            foreach (var c in e.Constraints)
            {
                md.AppendLine($"- {c}");
            }

            md.AppendLine();
        }

        md.AppendLine($"Accessibility: role `{e.Accessibility.Role}`; {e.Accessibility.Keyboard}").AppendLine();
    }
}

outputs["docs/reference/element-catalog.md"] = md.ToString().TrimEnd() + "\n";

// 3. AsyncAPI 3.0 reference of the events the platform and the first-party modules' newest releases publish (ADR 0017).
var eventTypes = Esmbler.Kernel.Configuration.PlatformModule.EventTypes.Select(e => (Source: "core.platform", Type: e)).ToList();
foreach (var moduleDir in Directory.GetDirectories(Path.Combine(root, "modules")).Order(StringComparer.Ordinal))
{
    var releases = Directory.GetFiles(moduleDir, "module.json", SearchOption.AllDirectories)
        .Where(f => !f.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}", StringComparison.Ordinal) && !f.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
        .Select(f => JsonSerializer.Deserialize<ModuleSpec>(File.ReadAllText(f), SpecJson.Options)!)
        .OrderBy(m => Version.Parse(m.Version)).ToList();
    if (releases.Count > 0)
    {
        eventTypes.AddRange(releases[^1].EventTypes.Select(e => (Source: releases[^1].Id, Type: e)));
    }
}

var envelopeSchema = SpecJson.Options.GetJsonSchemaAsNode(typeof(Esmbler.Sdk.Events.EventEnvelope), new JsonSchemaExporterOptions { TreatNullObliviousAsNonNullable = true }).AsObject();
var channels = new JsonObject();
var operations = new JsonObject();
var messages = new JsonObject();
foreach (var (source, type) in eventTypes.OrderBy(e => e.Type.Id, StringComparer.Ordinal))
{
    var key = type.Id.Replace('.', '_');
    var payload = new JsonObject { ["type"] = "object", ["properties"] = new JsonObject(type.Fields.Select(f => KeyValuePair.Create<string, JsonNode?>(f.Key, PayloadSchema(f.Value)))) };
    if (type.Fields.Any(f => f.Value.Required))
    {
        payload["required"] = new JsonArray(type.Fields.Where(f => f.Value.Required).Select(f => (JsonNode?)JsonValue.Create(f.Key)).ToArray());
    }

    messages[key] = new JsonObject
    {
        ["name"] = type.Id,
        ["title"] = type.Label,
        ["summary"] = type.Description ?? type.Label,
        ["contentType"] = "application/json",
        ["payload"] = new JsonObject
        {
            ["allOf"] = new JsonArray(
                new JsonObject { ["$ref"] = "#/components/schemas/EventEnvelope" },
                new JsonObject { ["properties"] = new JsonObject { ["type"] = new JsonObject { ["const"] = type.Id }, ["typeVersion"] = new JsonObject { ["const"] = type.Version }, ["payload"] = payload } }),
        },
        ["x-esmbler-source"] = source,
        ["x-esmbler-subject-entity"] = type.SubjectEntity,
        ["x-esmbler-severity"] = type.Severity,
        ["x-esmbler-sensitivity"] = type.Sensitivity,
        ["x-esmbler-category"] = type.Category,
    };
    channels[key] = new JsonObject { ["address"] = type.Id, ["messages"] = new JsonObject { [key] = new JsonObject { ["$ref"] = $"#/components/messages/{key}" } } };
    operations[$"publish_{key}"] = new JsonObject { ["action"] = "send", ["channel"] = new JsonObject { ["$ref"] = $"#/channels/{key}" }, ["summary"] = $"{source} publishes {type.Label.ToLowerInvariant()}." };
}

var asyncApi = new JsonObject
{
    ["asyncapi"] = "3.0.0",
    ["info"] = new JsonObject
    {
        ["title"] = "Esmbler events",
        ["version"] = "2",
        ["description"] = "Events the platform and the newest first-party module releases publish through the transactional outbox (ADR 0017). Generated by tools/Esmbler.DocGen; do not edit. Tenants add their own event types at runtime (tenant__ IDs); list them with the MCP tool list_event_types.",
    },
    ["channels"] = channels,
    ["operations"] = operations,
    ["components"] = new JsonObject { ["schemas"] = new JsonObject { ["EventEnvelope"] = envelopeSchema }, ["messages"] = messages },
};
outputs["docs/reference/asyncapi.json"] = asyncApi.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";

var stale = new List<string>();
foreach (var (relative, content) in outputs)
{
    var path = Path.Combine(root, relative);
    var existing = File.Exists(path) ? File.ReadAllText(path) : null;
    if (existing == content)
    {
        continue;
    }

    if (check)
    {
        stale.Add(relative);
    }
    else
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
        Console.WriteLine($"wrote {relative}");
    }
}

if (stale.Count > 0)
{
    Console.Error.WriteLine("Generated references are stale. Run: dotnet run --project tools/Esmbler.DocGen");
    stale.ForEach(s => Console.Error.WriteLine("  " + s));
    return 1;
}

Console.WriteLine(check ? "Generated references are current." : $"{outputs.Count} reference files up to date.");
return 0;

static JsonObject PayloadSchema(EventFieldSpec field)
{
    var schema = field.Type switch
    {
        EventFieldTypes.Number => new JsonObject { ["type"] = "number" },
        EventFieldTypes.Boolean => new JsonObject { ["type"] = "boolean" },
        EventFieldTypes.List => new JsonObject { ["type"] = "array" },
        _ => new JsonObject { ["type"] = "string" },
    };
    if (field.Description is { } d)
    {
        schema["description"] = d;
    }

    return schema;
}

static string FindRoot()
{
    var dir = new DirectoryInfo(AppContext.BaseDirectory);
    while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "Esmbler.slnx")))
    {
        dir = dir.Parent;
    }

    return dir?.FullName ?? Directory.GetCurrentDirectory();
}

static int CategoryOrder(string c) => Array.IndexOf(["layout", "field", "field_type", "display", "collection", "activity", "action", "feedback", "spec_object"], c);

static string CategoryTitle(string c) => c switch
{
    "layout" => "Layout",
    "field" => "Field placement",
    "field_type" => "Field types",
    "display" => "Display",
    "collection" => "Collections",
    "activity" => "Record activity",
    "action" => "Actions",
    "feedback" => "Feedback",
    _ => "Spec objects",
};

static string FirstSentence(string s)
{
    var i = s.IndexOf(". ", StringComparison.Ordinal);
    return i > 0 ? s[..(i + 1)] : s;
}

static string Escape(string s) => s.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);

static string List(List<string> items) => items.Count == 0 ? "none" : string.Join(", ", items.Select(i => $"`{i}`"));

static string TypeOf(JsonNode? schema) => schema switch
{
    JsonObject o when o["enum"] is JsonArray en => string.Join(" | ", en.Select(v => v?.ToJsonString() ?? "null")),
    JsonObject o when o["type"] is JsonValue t => t.ToString(),
    JsonObject o when o["type"] is JsonArray ta => string.Join(" or ", ta.Select(v => v!.ToString())),
    JsonObject o when o["$ref"] is not null => "ref",
    _ => "any",
};
